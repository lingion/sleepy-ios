    private static let FIRST_LETTER: [String?] = {
        var arr = [String?](repeating: nil, count: 20902)
        for (ch, letter) in BASIC_MAP {
            let code = Int(ch.unicodeScalars.first!.value)
            if (0x4E00...0x9FA5).contains(code) {
                arr[code - 0x4E00] = letter
            }
        }
        return arr
    }()

    static func firstLetterOf(_ ch: Character) -> String? {
        guard let scalar = ch.unicodeScalars.first else { return nil }
        // ← ch in '一'..'鿿' (0x4E00..0x9FFF)
        guard (0x4E00...0x9FFF).contains(scalar.value) else { return nil }
        let idx = Int(scalar.value) - 0x4E00
        return idx >= 0 && idx < FIRST_LETTER.count ? FIRST_LETTER[idx] : nil
    }

    static func namePinyinShort(_ name: String, _ sortKey: String) -> String {
        var sb = ""
        if sortKey.count == 1, let c = sortKey.first, c.isLetter {
            sb.append(c.lowercased())
        }
        for ch in name {
            // ← ch in 'a'..'z' || ch in 'A'..'Z' || ch in '0'..'9'
            if ch.isASCII && (ch.isLetter || ch.isNumber) {
                sb.append(String(ch).lowercased())
            } else if let fl = firstLetterOf(ch) {
                sb.append(fl.lowercased())
            }
        }
        return sb
    }

    static func match(_ name: String, _ sortKey: String, _ query: String, aliases: [String] = []) -> Bool {
        if query.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return true }
        let q = query.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        if name.lowercased().contains(q) { return true }
        if aliases.contains(where: { $0.lowercased().contains(q) }) { return true }
        let py = namePinyinShort(name, sortKey)
        return py.contains(q)
    }

