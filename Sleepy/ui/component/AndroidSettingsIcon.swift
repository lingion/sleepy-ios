import SwiftUI

/// Exact Outlined vectors used by Android 1.0.64 settings entry points.
/// Source: AndroidX Compose Material Icons 1.7.8 official sources, 24-unit viewport.
struct AndroidSettingsIcon: View {
    enum Name {
        case edit, schedule, dateRange, notifications, palette, tune, widgets, saveAlt, info, autoAwesome
        case close, delete, expandMore, expandLess, arrowBack, checkCircle, removeCircleOutline
        case refresh
        case fileUpload, share, newReleases, bugReport, openInNew, email, groups, contentCopy, person, code
        case shield, star, smartToy, locationOn, classroom, accessTime, school, arrowForward
        case settings, qrCode2, description, link, phoneAndroid, computer
    }

    @Environment(\.layoutDirection) private var layoutDirection
    let name: Name
    var size: CGFloat = 24

    var body: some View {
        AndroidVectorShape(vector: vector)
            .fill()
            .frame(width: size, height: size)
            .scaleEffect(x: mirrorsInRTL && layoutDirection == .rightToLeft ? -1 : 1, y: 1)
            .accessibilityHidden(true)
    }

    private var mirrorsInRTL: Bool {
        name == .arrowBack || name == .openInNew || name == .arrowForward
    }

    private var vector: Path {
        switch name {
        case .edit: return AndroidSettingsIconGeometry.edit
        case .schedule: return AndroidSettingsIconGeometry.schedule
        case .dateRange: return AndroidSettingsIconGeometry.dateRange
        case .notifications: return AndroidSettingsIconGeometry.notifications
        case .palette: return AndroidSettingsIconGeometry.palette
        case .tune: return AndroidSettingsIconGeometry.tune
        case .widgets: return AndroidSettingsIconGeometry.widgets
        case .saveAlt: return AndroidSettingsIconGeometry.saveAlt
        case .info: return AndroidSettingsIconGeometry.info
        case .autoAwesome: return AndroidSettingsIconGeometry.autoAwesome
        case .close: return AndroidSettingsIconGeometry.close
        case .delete: return AndroidSettingsIconGeometry.delete
        case .expandMore: return AndroidSettingsIconGeometry.expandMore
        case .expandLess: return AndroidSettingsIconGeometry.expandLess
        case .arrowBack: return AndroidSettingsIconGeometry.arrowBack
        case .checkCircle: return AndroidSettingsIconGeometry.checkCircle
        case .removeCircleOutline: return AndroidSettingsIconGeometry.removeCircleOutline
        case .refresh: return AndroidSettingsIconGeometry.refresh
        case .fileUpload: return AndroidSettingsIconGeometry.fileUpload
        case .share: return AndroidSettingsIconGeometry.share
        case .newReleases: return AndroidSettingsIconGeometry.newReleases
        case .bugReport: return AndroidSettingsIconGeometry.bugReport
        case .openInNew: return AndroidSettingsIconGeometry.openInNew
        case .email: return AndroidSettingsIconGeometry.email
        case .groups: return AndroidSettingsIconGeometry.groups
        case .contentCopy: return AndroidSettingsIconGeometry.contentCopy
        case .person: return AndroidSettingsIconGeometry.person
        case .code: return AndroidSettingsIconGeometry.code
        case .shield: return AndroidSettingsIconGeometry.shield
        case .star: return AndroidSettingsIconGeometry.star
        case .smartToy: return AndroidSettingsIconGeometry.smartToy
        case .locationOn: return AndroidSettingsIconGeometry.locationOn
        case .classroom: return AndroidSettingsIconGeometry.classroom
        case .accessTime: return AndroidSettingsIconGeometry.accessTime
        case .school: return AndroidSettingsIconGeometry.school
        case .arrowForward: return AndroidSettingsIconGeometry.arrowForward
        case .settings: return AndroidSettingsIconGeometry.settings
        case .qrCode2: return AndroidSettingsIconGeometry.qrCode2
        case .description: return AndroidSettingsIconGeometry.description
        case .link: return AndroidSettingsIconGeometry.link
        case .phoneAndroid: return AndroidSettingsIconGeometry.phoneAndroid
